//! Admission-fenced observations from a *separate*, trusted pytest worker.
//! This module never launches pytest or infers results from stdout or filenames.

use crate::digest::{DigestInput, valid_sha256};
use crate::project::{SelectionContext, SelectionStatus};
use std::collections::{BTreeMap, BTreeSet};

const MAX_NODE_IDS: usize = 20_000;
const MAX_NODE_ID_BYTES: usize = 512;
const MAX_ATTEMPT_ARTIFACT_BYTES: u64 = 2 * 1024 * 1024;
const MAX_OBSERVATION_BYTES: usize = 2 * 1024 * 1024;
const MAX_EXCERPT_BYTES: usize = 4_096;
const MAX_FAILURE_BYTES: usize = 256;
const TIMESTAMP_TOLERANCE_MS: u64 = 2_000;

/// External identity stamps are supplied and attested by the approved worker
/// coordinator. Digests bind bytes but do not authenticate an untrusted worker.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ReceiptBinding {
    pub attempt_id: String,
    pub project_root: String,
    pub scope_sha256: String,
    pub source_sha256: String,
    pub configuration_sha256: String,
    /// Effective pytest settings after the worker's plugin/configuration phase.
    pub effective_pytest_config_sha256: String,
    pub selection_sha256: String,
    pub interpreter_sha256: String,
    pub environment_sha256: String,
    pub pytest_sha256: String,
    pub plugins_sha256: String,
    /// Collected node IDs in the actual order returned by the worker.
    pub collected_ids_sha256: String,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Admission {
    pub binding: ReceiptBinding,
    /// Coordinator-observed process/lease interval, UNIX milliseconds.
    pub started_ms: u64,
    pub finished_ms: u64,
    /// An exclusive, empty-before-attempt artifact directory was granted.
    pub owned_directory: bool,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Process {
    MissingRunner,
    StartupFailure,
    Cancelled,
    TimedOut,
    Incomplete,
    Exited(i32),
}

/// Facts about a bounded, attributed report generated by the admitted worker.
/// The parse of raw JSON/XML belongs to that worker, *not* to this adapter.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Artifact {
    pub sha256: String,
    pub byte_count: u64,
    pub modified_ms: u64,
    pub output_excerpt: String,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Collected {
    pub process: Process,
    /// Worker confirms the final `pytest_collection_finish` and no collector errors.
    pub finished: bool,
    /// The worker actually traversed the whole admitted project root, not a
    /// prefiltered path/`-k` subset or just the lexical candidates.
    pub full_project_scope: bool,
    /// Any explicitly narrowed or deselected collection is not complete.
    pub filtered: bool,
    pub collection_errors: u32,
    pub node_ids: Vec<String>,
    pub artifact: Option<Artifact>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CaseOutcome {
    Passed,
    Failed,
    Skipped,
    XFailed,
    XPassed,
    Error,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PytestCase {
    pub node_id: String,
    /// One normalized *terminal* result for a collected item, combining
    /// setup/call/teardown and making an error dominate a prior pass.
    pub outcome: CaseOutcome,
    pub failure_excerpt: Option<String>,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Run {
    pub process: Process,
    /// Worker observed test-session completion, including teardown.
    pub finished: bool,
    pub cases: Vec<PytestCase>,
    pub artifact: Option<Artifact>,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct Observation {
    pub binding: ReceiptBinding,
    pub collection: Option<Collected>,
    pub run: Option<Run>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ReceiptDisposition {
    InvalidFacts,
    Stale,
    UnresolvedSelection,
    MissingRunner,
    StartupFailure,
    Cancelled,
    TimedOut,
    Incomplete,
    CollectionFailure,
    ZeroDiscovered,
    AllSkipped,
    Failed,
    Passed,
    RunnerFailure,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ReceiptResult {
    pub disposition: ReceiptDisposition,
    pub reason: &'static str,
    pub collected: usize,
    pub passed: usize,
    pub failed: usize,
    pub skipped: usize,
}

fn verdict(
    disposition: ReceiptDisposition,
    reason: &'static str,
    collected: usize,
    passed: usize,
    failed: usize,
    skipped: usize,
) -> ReceiptResult {
    ReceiptResult {
        disposition,
        reason,
        collected,
        passed,
        failed,
        skipped,
    }
}

fn simple(disposition: ReceiptDisposition, reason: &'static str) -> ReceiptResult {
    verdict(disposition, reason, 0, 0, 0, 0)
}

/// The digest is order-sensitive: a new pytest collection order invalidates
/// the admitted run as well as changes to the set of collected IDs.
pub fn node_ids_digest(node_ids: &[String]) -> String {
    let mut digest = DigestInput::new("slophawk/python/pytest-collected-ids/v1");
    for id in node_ids {
        digest.append(id.as_bytes());
    }
    digest.finish()
}

/// Returns conservative classifications rather than treating truncated facts,
/// missing tests or pytest's exit code 5 as proof of a successful test run.
pub fn classify_receipt(
    selection: &SelectionContext,
    admitted: &Admission,
    observed: &Observation,
) -> ReceiptResult {
    if selection.status != SelectionStatus::NeedsAdmittedCollection
        || !selection
            .impacted
            .iter()
            .any(|project| project.root == admitted.binding.project_root)
    {
        return simple(
            ReceiptDisposition::UnresolvedSelection,
            "project_scope_not_complete",
        );
    }
    let b = &admitted.binding;
    if !valid_code(&b.attempt_id)
        || !valid_project_path(&b.project_root)
        || [
            &b.scope_sha256,
            &b.source_sha256,
            &b.configuration_sha256,
            &b.effective_pytest_config_sha256,
            &b.selection_sha256,
            &b.interpreter_sha256,
            &b.environment_sha256,
            &b.pytest_sha256,
            &b.plugins_sha256,
            &b.collected_ids_sha256,
        ]
        .into_iter()
        .any(|value| !valid_sha256(value))
        || admitted.started_ms == 0
        || admitted.finished_ms < admitted.started_ms
    {
        return simple(ReceiptDisposition::InvalidFacts, "invalid_admission");
    }
    if b.scope_sha256 != selection.identity.scope_sha256
        || b.source_sha256 != selection.identity.source_sha256
        || b.configuration_sha256 != selection.identity.configuration_sha256
        || b.selection_sha256 != selection.selection_sha256
        || b != &observed.binding
    {
        return simple(
            ReceiptDisposition::Stale,
            "identity_or_environment_mismatch",
        );
    }
    if !admitted.owned_directory {
        return simple(ReceiptDisposition::Stale, "unowned_results_directory");
    }
    let Some(collection) = &observed.collection else {
        return simple(
            ReceiptDisposition::MissingRunner,
            "missing_collection_receipt",
        );
    };
    if let Some(disposition) = early_process(&collection.process) {
        return simple(disposition, "collection_process_not_completed");
    }
    let Some(artifact) = &collection.artifact else {
        return simple(
            ReceiptDisposition::InvalidFacts,
            "missing_collection_artifact",
        );
    };
    if !valid_artifact(artifact) {
        return simple(
            ReceiptDisposition::InvalidFacts,
            "invalid_collection_artifact",
        );
    }
    if !attributed(artifact, admitted) {
        return simple(ReceiptDisposition::Stale, "stale_collection_artifact");
    }
    if collection.node_ids.len() > MAX_NODE_IDS
        || collection
            .node_ids
            .iter()
            .fold(0usize, |n, id| n.saturating_add(id.len()))
            > MAX_OBSERVATION_BYTES
        || collection.node_ids.iter().any(|id| !valid_node_id(id))
        || !unique(&collection.node_ids)
    {
        return simple(
            ReceiptDisposition::InvalidFacts,
            "invalid_collected_node_ids",
        );
    }
    let count = collection.node_ids.len();
    if node_ids_digest(&collection.node_ids) != b.collected_ids_sha256 {
        return simple(ReceiptDisposition::Stale, "collected_ids_mismatch");
    }
    if !collection.full_project_scope || collection.filtered {
        return verdict(
            ReceiptDisposition::UnresolvedSelection,
            "filtered_or_partial_collection_scope",
            count,
            0,
            0,
            0,
        );
    }
    if collection.collection_errors != 0 || !collection.finished {
        return verdict(
            ReceiptDisposition::CollectionFailure,
            "incomplete_or_failed_collection",
            count,
            0,
            0,
            0,
        );
    }
    if !matches!(&collection.process, Process::Exited(0) | Process::Exited(5))
        || (count == 0 && collection.process != Process::Exited(5))
        || (count > 0 && collection.process != Process::Exited(0))
    {
        return verdict(
            ReceiptDisposition::CollectionFailure,
            "collection_exit_disagrees",
            count,
            0,
            0,
            0,
        );
    }
    // A complete, admitted, current *collection* can establish zero tests;
    // a source-only scan or a partial collection never can.
    if count == 0 {
        if observed.run.is_some() {
            return verdict(
                ReceiptDisposition::InvalidFacts,
                "run_for_empty_collection",
                count,
                0,
                0,
                0,
            );
        }
        return verdict(
            ReceiptDisposition::ZeroDiscovered,
            "admitted_collection_found_zero",
            0,
            0,
            0,
            0,
        );
    }
    let Some(run) = &observed.run else {
        return verdict(
            ReceiptDisposition::Incomplete,
            "missing_execution_receipt",
            count,
            0,
            0,
            0,
        );
    };
    if let Some(disposition) = early_process(&run.process) {
        return verdict(disposition, "run_process_not_completed", count, 0, 0, 0);
    }
    let Some(run_artifact) = &run.artifact else {
        return verdict(
            ReceiptDisposition::InvalidFacts,
            "missing_execution_artifact",
            count,
            0,
            0,
            0,
        );
    };
    if !valid_artifact(run_artifact) {
        return verdict(
            ReceiptDisposition::InvalidFacts,
            "invalid_execution_artifact",
            count,
            0,
            0,
            0,
        );
    }
    if !attributed(run_artifact, admitted) || run_artifact.modified_ms < artifact.modified_ms {
        return verdict(
            ReceiptDisposition::Stale,
            "stale_execution_artifact",
            count,
            0,
            0,
            0,
        );
    }
    if run.cases.len() > count || run.cases.len() > MAX_NODE_IDS {
        return verdict(
            ReceiptDisposition::InvalidFacts,
            "case_count_exceeds_collection",
            count,
            0,
            0,
            0,
        );
    }
    let mut cases = BTreeMap::new();
    let mut payload = 0usize;
    for case in &run.cases {
        if !valid_node_id(&case.node_id)
            || case
                .failure_excerpt
                .as_ref()
                .is_some_and(|excerpt| !valid_excerpt(excerpt, MAX_FAILURE_BYTES))
            || matches!(
                case.outcome,
                CaseOutcome::Passed | CaseOutcome::Skipped | CaseOutcome::XFailed
            ) && case.failure_excerpt.is_some()
            || cases.insert(&case.node_id, case.outcome).is_some()
        {
            return verdict(
                ReceiptDisposition::InvalidFacts,
                "malformed_case",
                count,
                0,
                0,
                0,
            );
        }
        payload = payload
            .saturating_add(case.node_id.len())
            .saturating_add(case.failure_excerpt.as_ref().map_or(0, String::len));
    }
    if payload > MAX_OBSERVATION_BYTES
        || cases
            .keys()
            .any(|node| !collection.node_ids.iter().any(|found| found == *node))
    {
        return verdict(
            ReceiptDisposition::InvalidFacts,
            "uncollected_or_oversized_case",
            count,
            0,
            0,
            0,
        );
    }
    let mut passed = 0;
    let mut failed = 0;
    let mut skipped = 0;
    for outcome in cases.values() {
        match outcome {
            CaseOutcome::Passed => passed += 1,
            CaseOutcome::Failed | CaseOutcome::XPassed | CaseOutcome::Error => failed += 1,
            CaseOutcome::Skipped | CaseOutcome::XFailed => skipped += 1,
        }
    }
    if !run.finished || cases.len() != count {
        return verdict(
            ReceiptDisposition::Incomplete,
            "run_missing_terminal_cases",
            count,
            passed,
            failed,
            skipped,
        );
    }
    match &run.process {
        Process::Exited(0) if failed == 0 && passed > 0 => verdict(
            ReceiptDisposition::Passed,
            "admitted_cases_passed",
            count,
            passed,
            failed,
            skipped,
        ),
        Process::Exited(0) if failed == 0 && passed == 0 && skipped == count => verdict(
            ReceiptDisposition::AllSkipped,
            "all_collected_cases_skipped",
            count,
            passed,
            failed,
            skipped,
        ),
        Process::Exited(1) if failed > 0 => verdict(
            ReceiptDisposition::Failed,
            "observed_failed_cases",
            count,
            passed,
            failed,
            skipped,
        ),
        Process::Exited(0) if failed > 0 => verdict(
            ReceiptDisposition::InvalidFacts,
            "failed_cases_with_zero_exit",
            count,
            passed,
            failed,
            skipped,
        ),
        Process::Exited(_) => verdict(
            ReceiptDisposition::RunnerFailure,
            "runner_exit_contradicts_cases",
            count,
            passed,
            failed,
            skipped,
        ),
        _ => unreachable!("nonterminal process was handled above"),
    }
}

fn early_process(process: &Process) -> Option<ReceiptDisposition> {
    match process {
        Process::MissingRunner => Some(ReceiptDisposition::MissingRunner),
        Process::StartupFailure => Some(ReceiptDisposition::StartupFailure),
        Process::Cancelled => Some(ReceiptDisposition::Cancelled),
        Process::TimedOut => Some(ReceiptDisposition::TimedOut),
        Process::Incomplete => Some(ReceiptDisposition::Incomplete),
        Process::Exited(_) => None,
    }
}

fn valid_artifact(artifact: &Artifact) -> bool {
    valid_sha256(&artifact.sha256)
        && artifact.byte_count > 0
        && artifact.byte_count <= MAX_ATTEMPT_ARTIFACT_BYTES
        && valid_excerpt(&artifact.output_excerpt, MAX_EXCERPT_BYTES)
}

fn attributed(artifact: &Artifact, admission: &Admission) -> bool {
    artifact.modified_ms >= admission.started_ms
        && artifact.modified_ms <= admission.finished_ms.saturating_add(TIMESTAMP_TOLERANCE_MS)
}

fn valid_code(text: &str) -> bool {
    !text.is_empty()
        && text.len() <= 64
        && text
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'_' | b'-' | b'.'))
}

fn valid_project_path(path: &str) -> bool {
    path == "." || valid_relative_path(path)
}

fn valid_relative_path(path: &str) -> bool {
    !path.is_empty()
        && path.len() <= 1024
        && !path.starts_with('/')
        && !path.chars().any(|ch| matches!(ch, '\\' | ':'))
        && !path.bytes().any(|b| b.is_ascii_control())
        && path
            .split('/')
            .all(|part| !part.is_empty() && part != "." && part != "..")
}

fn valid_node_id(node: &str) -> bool {
    if node.is_empty() || node.len() > MAX_NODE_ID_BYTES {
        return false;
    }
    let mut parts = node.split("::");
    let Some(path) = parts.next() else {
        return false;
    };
    valid_relative_path(path)
        && parts.all(|part| !part.is_empty() && !part.bytes().any(|b| b.is_ascii_control()))
}

fn valid_excerpt(text: &str, cap: usize) -> bool {
    text.len() <= cap
        && text
            .chars()
            .all(|ch| !ch.is_control() || matches!(ch, '\n' | '\t' | '\r'))
}

fn unique(values: &[String]) -> bool {
    let mut set = BTreeSet::new();
    values.iter().all(|value| set.insert(value.as_str()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn node_ids_are_order_sensitive() {
        let first = vec!["a.py::test_1".into(), "a.py::test_2".into()];
        let second = vec!["a.py::test_2".into(), "a.py::test_1".into()];
        assert_ne!(node_ids_digest(&first), node_ids_digest(&second));
        assert!(valid_node_id("tests/test_api.py::test_ok[windows-3]"));
        assert!(!valid_node_id("../other/test_api.py::test_ok"));
    }
}
