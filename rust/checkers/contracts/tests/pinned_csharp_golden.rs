//! Golden ordered input traces emitted by pinned C# `ProbeReplay.Plan` under
//! the portable .NET 10.0.404 SDK, prior to native Rust integration.
//! Inputs/outputs are captured in the batch report; no JSON parser needed.
use slophawk_contracts::{ProbeInput, plan_inputs};

fn input(op: &str, args: &[i64]) -> ProbeInput {
    ProbeInput {
        operation: op.to_owned(),
        args: args.to_vec(),
    }
}

fn compare(
    inputs: &[ProbeInput],
    limit: usize,
    seed: i32,
    scales: &[i64],
    expected: &[(&str, &[i64])],
) {
    let observed = plan_inputs(inputs, limit, seed, scales).unwrap();
    let flattened = observed
        .iter()
        .map(|row| (row.operation.as_str(), row.args.as_slice()))
        .collect::<Vec<_>>();
    assert_eq!(flattened, expected);
}

#[test]
fn csharp_plan_arities() {
    let seeds = [
        input("b", &[1]),
        input("a", &[]),
        input("b", &[10, 20]),
        input("b", &[1]),
    ];
    compare(
        &seeds,
        12,
        1,
        &[],
        &[
            ("b", &[1]),
            ("b", &[10, 20]),
            ("b", &[9, 20]),
            ("b", &[0]),
            ("b", &[10, 10]),
            ("b", &[20, 0]),
            ("b", &[10, 19]),
            ("b", &[2]),
            ("b", &[20, 20]),
            ("b", &[4, 11]),
            ("b", &[4]),
            ("b", &[11, 20]),
            ("a", &[]),
        ],
    );
}

